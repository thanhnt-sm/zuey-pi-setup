"""Optional C# syntax and runtime-evidence adapters for Phase 1.

Tree-sitter is deliberately syntax-only.  This module never claims Roslyn binding,
complete runtime coverage, or database constraint evidence.
"""
from __future__ import annotations

import json
import os
import re
import shutil
from functools import lru_cache
from pathlib import Path

try:
    import tree_sitter_c_sharp
    from tree_sitter import Language, Parser
except (ImportError, TypeError):  # Optional dependency; regex remains the fallback.
    Language = Parser = tree_sitter_c_sharp = None


_GENERATED_MARKER = re.compile(r"<auto-generated\b|\[\s*GeneratedCode\s*\(", re.IGNORECASE)
_GENERATED_DIRECTORY_NAMES = {"obj", "bin", "generated", "generatedcode"}
_REFLECTION_NAMES = {
    "Activator.CreateInstance",
    "CreateInstance",
    "GetConstructor",
    "GetMethod",
    "GetProperty",
    "Invoke",
    "InvokeMember",
    "Type.GetType",
}
_TYPE_DECLARATIONS = {
    "class_declaration",
    "record_declaration",
    "struct_declaration",
    "interface_declaration",
    "enum_declaration",
}
_METHOD_DECLARATIONS = {"method_declaration", "constructor_declaration"}


@lru_cache(maxsize=1)
def _language():
    if Language is None or tree_sitter_c_sharp is None:
        return None
    try:
        return Language(tree_sitter_c_sharp.language())
    except (TypeError, ValueError):
        return None


def parser_capabilities():
    language = _language()
    return {
        "ast": {
            "available": language is not None,
            "engine": "tree-sitter-c-sharp" if language is not None else "none",
            "reason": "installed" if language is not None else "optional tree-sitter-c-sharp package unavailable",
        },
        "regexFallback": {
            "available": True,
            "engine": "python-regex",
            "reason": "always available as conservative fallback",
        },
    }


def _dotnet_path():
    return shutil.which("dotnet")


def _roslyn_assembly_state():
    dotnet_path = _dotnet_path()
    roots = []
    for value in (os.environ.get("DOTNET_ROOT"), os.environ.get("ProgramFiles")):
        if value:
            roots.append(Path(value) / "dotnet")
    roots.append(Path("C:/Program Files/dotnet"))
    candidates = []
    for root in roots:
        sdk_root = root / "sdk"
        if not sdk_root.is_dir():
            continue
        candidates.extend(sorted(sdk_root.glob("*/Roslyn/bincore/Microsoft.CodeAnalysis.CSharp.dll")))
    compiler = sorted({str(path.resolve()) for path in candidates}, key=str.lower)
    workspace = []
    for compiler_path in compiler:
        sdk_root = Path(compiler_path).parents[2]
        workspace_path = sdk_root / "DotnetTools" / "dotnet-format" / "Microsoft.CodeAnalysis.Workspaces.MSBuild.dll"
        if workspace_path.is_file():
            workspace.append(str(workspace_path.resolve()))
    return {
        "dotnet": dotnet_path or "",
        "compilerAssemblies": compiler,
        "workspaceAssemblies": sorted(set(workspace), key=str.lower),
    }


def analyzer_capabilities(solution=None, project=None, runtime_evidence=None):
    roslyn = _roslyn_assembly_state()
    solution_path = Path(solution).resolve() if solution else None
    project_path = Path(project).resolve() if project else None
    project_input = solution_path or project_path
    input_exists = bool(project_input and project_input.is_file())
    semantic_ready = bool(
        input_exists
        and roslyn["dotnet"]
        and roslyn["compilerAssemblies"]
        and roslyn["workspaceAssemblies"]
    )
    if not project_input:
        semantic_reason = "solution-or-project-not-supplied"
    elif not input_exists:
        semantic_reason = "solution-or-project-does-not-exist"
    elif semantic_ready:
        semantic_reason = "Roslyn assemblies detected; semantic overlay remains opt-in and is not run by default"
    else:
        semantic_reason = "required Roslyn/MSBuildWorkspace assemblies not detected"
    runtime_requested = bool(runtime_evidence)
    return {
        **parser_capabilities(),
        "compiler": {
            "available": semantic_ready,
            "selected": False,
            "engine": "Roslyn SemanticModel/MSBuildWorkspace",
            "reason": semantic_reason,
            "dotnet": roslyn["dotnet"],
            "input": str(project_input) if project_input else "",
            "workspaceAssemblyCount": len(roslyn["workspaceAssemblies"]),
        },
        "runtime": {
            "available": True,
            "selected": runtime_requested,
            "engine": "normalized-runtime-evidence",
            "reason": "normalized JSON supplied" if runtime_requested else "not requested",
        },
        "selectedEngine": "tree-sitter-c-sharp" if parser_capabilities()["ast"]["available"] else "python-regex",
    }


def generated_source_reason(text, path=None):
    if _GENERATED_MARKER.search("\n".join(text.splitlines()[:80])):
        return "generated-marker"
    if path:
        parts = {part.lower() for part in Path(path).parts}
        if parts & _GENERATED_DIRECTORY_NAMES:
            return "generated-path"
    return ""


def is_generated_source(text, path=None):
    return bool(generated_source_reason(text, path))


def _node_text(source, node):
    if node is None:
        return ""
    return source[node.start_byte : node.end_byte].decode("utf-8", errors="replace")


def _named_children(node):
    return list(getattr(node, "named_children", ()) or ())


def _descendants(node):
    for child in _named_children(node):
        yield child
        yield from _descendants(child)


def _node_name(source, node):
    name = node.child_by_field_name("name") if node is not None else None
    if name is None:
        return ""
    if name.type == "generic_name":
        identifier = next((child for child in _named_children(name) if child.type == "identifier"), None)
        return _node_text(source, identifier or name)
    return _node_text(source, name).strip()


def _type_name(source, node):
    type_node = node.child_by_field_name("type") if node is not None else None
    if type_node is None:
        return ""
    return _node_text(source, type_node).strip()


def _split_parameter_text(raw):
    raw = raw.strip()
    if raw.startswith("(") and raw.endswith(")"):
        raw = raw[1:-1]
    parts = []
    start = 0
    angle = paren = bracket = brace = 0
    quote = None
    escaped = False
    for index, char in enumerate(raw):
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            continue
        if char in {"\"", "'"}:
            quote = char
        elif char == "<":
            angle += 1
        elif char == ">":
            angle = max(0, angle - 1)
        elif char == "(":
            paren += 1
        elif char == ")":
            paren = max(0, paren - 1)
        elif char == "[":
            bracket += 1
        elif char == "]":
            bracket = max(0, bracket - 1)
        elif char == "{":
            brace += 1
        elif char == "}":
            brace = max(0, brace - 1)
        elif char == "," and not any((angle, paren, bracket, brace)):
            parts.append(raw[start:index].strip())
            start = index + 1
    tail = raw[start:].strip()
    if tail:
        parts.append(tail)
    return parts


def _fallback_parameters(raw):
    result = []
    for item in _split_parameter_text(raw):
        optional = bool(re.search(r"(?<![=<>!])=(?!=|>)", item))
        declaration = re.split(r"(?<![=<>!])=(?!=|>)", item, maxsplit=1)[0].strip()
        name_match = re.search(r"([A-Za-z_]\w*)\s*$", declaration)
        if not name_match:
            continue
        name = name_match.group(1)
        prefix = declaration[: name_match.start()].strip()
        modifiers = re.findall(r"\b(?:this|ref|out|in|params|scoped|readonly)\b", prefix)
        type_name = re.sub(
            r"\b(?:this|ref|out|in|params|scoped|readonly)\b",
            "",
            prefix,
        ).strip()
        result.append(
            {
                "name": name,
                "type": type_name,
                "optional": optional,
                "params": "params" in modifiers,
            }
        )
    return result


def _parameters(source, node):
    parameters = node.child_by_field_name("parameters") if node is not None else None
    if parameters is None:
        return []
    result = []
    for parameter in _named_children(parameters):
        if parameter.type not in {"parameter", "this_parameter", "property_pattern_clause"}:
            continue
        name_node = parameter.child_by_field_name("name")
        raw = _node_text(source, parameter).strip()
        name = _node_text(source, name_node).strip() if name_node else ""
        type_name = _type_name(source, parameter)
        if not type_name and name:
            prefix = raw.rsplit(name, 1)[0].strip()
            type_name = re.sub(r"\b(?:this|ref|out|in|params)\b", "", prefix).strip()
        result.append(
            {
                "name": name,
                "type": type_name,
                "optional": "=" in raw,
                "params": bool(re.search(r"\bparams\b", raw)),
            }
        )
    raw_parameters = _node_text(source, parameters)
    if len(result) != len(_split_parameter_text(raw_parameters)):
        return _fallback_parameters(raw_parameters)
    return result


def _invocation_name(source, function):
    if function is None:
        return ""
    if function.type == "member_access_expression":
        name_node = function.child_by_field_name("name")
    else:
        name_node = function
    name = _node_text(source, name_node).strip() if name_node else _node_text(source, function).strip()
    if name.startswith("<"):
        return ""
    return re.split(r"\s*<", name, maxsplit=1)[0]


def _invocation_receiver(source, function):
    if function is None or function.type != "member_access_expression":
        return None
    expression = function.child_by_field_name("expression")
    return _node_text(source, expression).strip() if expression else None


def _invocations(source, body_node):
    result = []
    for node in _descendants(body_node):
        if node.type != "invocation_expression":
            continue
        function = node.child_by_field_name("function")
        arguments = node.child_by_field_name("arguments")
        name = _invocation_name(source, function)
        if not name:
            continue
        receiver = _invocation_receiver(source, function)
        argument_count = len(_named_children(arguments)) if arguments is not None else 0
        result.append(
            {
                "name": name,
                "receiver": receiver,
                "argumentCount": argument_count,
                "line": node.start_point[0] + 1,
                "column": node.start_point[1] + 1,
                "symbol": _node_text(source, function).strip(),
            }
        )
    return result


def _risk_flags(source, body_node, invocations=None):
    identifiers = {
        _node_text(source, node).strip()
        for node in _descendants(body_node)
        if node.type in {"identifier", "predefined_type", "type_identifier"}
    }
    invocations = invocations if invocations is not None else _invocations(source, body_node)
    calls = {
        item["name"]
        for item in invocations
        if item.get("name")
    }
    flags = []
    if "dynamic" in identifiers:
        flags.append("dynamic")
    if calls & {name.rsplit(".", 1)[-1] for name in _REFLECTION_NAMES}:
        flags.append("reflection")
    return flags


def _class_base(source, node):
    bases = node.child_by_field_name("bases") if node is not None else None
    if bases is None:
        return ""
    raw = _node_text(source, bases).strip()
    first = raw.split(",", 1)[0].strip()
    return re.split(r"[<.\s]", first, maxsplit=1)[0]


def _method_record(source, node, class_name, class_base):
    kind = "constructor" if node.type == "constructor_declaration" else "method"
    name = _node_name(source, node)
    parameters = _parameters(source, node)
    body_node = node.child_by_field_name("body")
    arrow_node = body_node if body_node is not None and body_node.type == "arrow_expression_clause" else None
    if body_node is None:
        arrow_node = next(
            (child for child in _named_children(node) if child.type == "arrow_expression_clause"),
            None,
        )
    expression_bodied = arrow_node is not None and arrow_node.type == "arrow_expression_clause"
    if body_node is not None and body_node.type == "block":
        body = source[body_node.start_byte + 1 : max(body_node.start_byte + 1, body_node.end_byte - 1)].decode("utf-8", errors="replace")
        body_offset = body_node.start_byte + 1
    elif expression_bodied:
        expression = next(iter(_named_children(arrow_node)), None)
        expression_text = _node_text(source, expression or arrow_node).strip()
        returns = _node_text(source, node.child_by_field_name("returns")).strip()
        body = f"return {expression_text};" if returns and returns != "void" else f"{expression_text};"
        body_offset = arrow_node.start_byte
    else:
        body = ""
        body_offset = node.end_byte
    return_type = _node_text(source, node.child_by_field_name("returns")).strip()
    if kind == "constructor":
        return_type = ""
    modifiers = _node_text(source, node.child_by_field_name("modifiers")).strip()
    is_extension = bool(parameters and re.search(r"\bthis\b", _node_text(source, node.child_by_field_name("parameters"))))
    invocations = _invocations(source, body_node or arrow_node or node)
    parameter_types = ",".join(item["type"] or "?" for item in parameters)
    overload_key = f"{name}/{len(parameters)}({parameter_types})"
    return {
        "name": name,
        "return": return_type,
        "body": body,
        "bodyOffset": body_offset,
        "startOffset": node.start_byte,
        "endOffset": node.end_byte,
        "line": node.start_point[0] + 1,
        "kind": kind,
        "provenance": "AST_EXTRACTED",
        "parameters": parameters,
        "parameterCount": len(parameters),
        "overloadKey": overload_key,
        "signature": f"{return_type or 'constructor'} {name}({parameter_types})",
        "expressionBodied": expression_bodied,
        "invocations": invocations,
        "riskFlags": _risk_flags(source, body_node or arrow_node or node, invocations),
        "isExtension": is_extension,
        "class": class_name,
        "base": class_base,
        "modifiers": modifiers,
        "sourceSpan": {
            "startLine": node.start_point[0] + 1,
            "startColumn": node.start_point[1] + 1,
            "endLine": node.end_point[0] + 1,
            "endColumn": node.end_point[1] + 1,
        },
    }


def parse_methods(text, path=None):
    """Return AST method records, or ``None`` when optional parser is unavailable."""
    if _language() is None:
        return None
    if is_generated_source(text, path):
        return []
    try:
        parser = Parser()
        parser.language = _language()
        source = text.encode("utf-8")
        tree = parser.parse(source)
        records = []

        def visit(node, inherited_class="", inherited_base=""):
            if node.type in _TYPE_DECLARATIONS:
                class_name = _node_name(source, node) or inherited_class
                class_base = _class_base(source, node) or inherited_base
                body = node.child_by_field_name("body")
                if body is not None:
                    for child in _named_children(body):
                        if child.type in _METHOD_DECLARATIONS:
                            records.append(_method_record(source, child, class_name, class_base))
                        elif child.type in _TYPE_DECLARATIONS:
                            visit(child, class_name, class_base)
                return
            for child in _named_children(node):
                visit(child, inherited_class, inherited_base)

        visit(tree.root_node)
        return sorted(records, key=lambda item: (item["startOffset"], item["name"], item["overloadKey"]))
    except (OSError, RuntimeError, TypeError, ValueError, UnicodeError):
        return None


def load_runtime_evidence(path, method_ids):
    """Load only normalized JSON runtime evidence; never parse binary EventPipe files."""
    path = Path(path)
    if path.suffix.lower() != ".json":
        raise ValueError("runtime evidence must be normalized JSON; binary EventPipe .nettrace is unsupported")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise ValueError(f"invalid normalized runtime evidence: {error}") from error
    if not isinstance(payload, dict) or payload.get("schemaVersion") != 1:
        raise ValueError("runtime evidence schemaVersion must be 1")
    source_hash = payload.get("sourceHash")
    events = payload.get("events")
    if not isinstance(source_hash, str) or not source_hash.strip():
        raise ValueError("runtime evidence sourceHash is required")
    if not isinstance(events, list):
        raise TypeError("runtime evidence events must be an array")
    method_ids = set(method_ids)
    accepted, unmatched = [], []
    for index, event in enumerate(events):
        if not isinstance(event, dict):
            raise TypeError(f"runtime evidence event {index} must be an object")
        caller = event.get("caller")
        callee = event.get("callee")
        if not isinstance(caller, str) or not isinstance(callee, str):
            raise TypeError(f"runtime evidence event {index} requires caller and callee strings")
        sample_count = event.get("sampleCount", 1)
        if not isinstance(sample_count, int) or sample_count < 1:
            raise ValueError(f"runtime evidence event {index} sampleCount must be a positive integer")
        normalized = {
            "id": f"runtime-{index:06d}",
            "caller": caller,
            "callee": callee,
            "status": "observed",
            "provenance": "RUNTIME_OBSERVED",
            "source": str(event.get("source", ""))[:200],
            "timestamp": str(event.get("timestamp", ""))[:80],
            "sampleCount": sample_count,
            "sourceHash": source_hash,
        }
        if event.get("processId") is not None:
            normalized["processId"] = str(event["processId"])[:80]
        if caller in method_ids and callee in method_ids:
            accepted.append(normalized)
        else:
            normalized["reason"] = "method-id-not-found"
            unmatched.append(normalized)
    return {
        "schemaVersion": 1,
        "sourceHash": source_hash,
        "events": accepted,
        "unmatched": unmatched,
    }
